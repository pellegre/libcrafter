#[derive(Clone, Default)]
struct SharedQlog(Arc<Mutex<Vec<u8>>>);

impl Write for SharedQlog {
    fn write(&mut self, data: &[u8]) -> io::Result<usize> {
        self.0.lock().unwrap().extend_from_slice(data);
        Ok(data.len())
    }

    fn flush(&mut self) -> io::Result<()> {
        Ok(())
    }
}

#[test]
fn provider_api_is_socket_agnostic() {
    let now = Instant::now();
    let client_addr = SocketAddr::from((Ipv4Addr::new(192, 0, 2, 10), 44444));
    let server_addr = SocketAddr::from((Ipv4Addr::new(198, 51, 100, 20), 4433));
    let certificate = CertificateDer::from(CERT_DER.to_vec());

    let mut roots = rustls::RootCertStore::empty();
    roots.add(certificate.clone()).unwrap();
    let mut client_config = ClientConfig::with_root_certificates(Arc::new(roots)).unwrap();

    let qlog = SharedQlog::default();
    let mut qlog_config = QlogConfig::default();
    qlog_config
        .writer(Box::new(qlog.clone()))
        .title(Some("socket-free provider API probe".into()))
        .start_time(now);
    let mut transport = TransportConfig::default();
    transport
        .enable_segmentation_offload(false)
        .qlog_stream(qlog_config.into_stream());
    client_config.transport_config(Arc::new(transport));

    let key = PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(KEY_DER.to_vec()));
    let server_config = ServerConfig::with_single_cert(vec![certificate], key).unwrap();

    let mut endpoint_config = EndpointConfig::default();
    endpoint_config.rng_seed(Some([0x42; 32]));
    let endpoint_config = Arc::new(endpoint_config);
    let mut client_endpoint = Endpoint::new(endpoint_config.clone(), None, false, None);
    let mut server_endpoint =
        Endpoint::new(endpoint_config, Some(Arc::new(server_config)), false, None);

    let (_, mut client) = client_endpoint
        .connect(now, client_config, server_addr, "quic.example")
        .unwrap();

    // The caller owns egress buffers, datagram transport, address metadata, and time.
    let mut outbound = Vec::new();
    let transmit = client.poll_transmit(now, 1, &mut outbound).unwrap();
    assert_eq!(transmit.destination, server_addr);
    assert!(transmit.size >= 1200);

    let mut endpoint_buffer = Vec::new();
    let event = server_endpoint.handle(
        now,
        client_addr,
        Some(IpAddr::V4(match server_addr.ip() {
            IpAddr::V4(address) => address,
            IpAddr::V6(_) => unreachable!(),
        })),
        None,
        BytesMut::from(&outbound[..transmit.size]),
        &mut endpoint_buffer,
    );
    let incoming = match event {
        Some(DatagramEvent::NewConnection(incoming)) => incoming,
        _ => panic!("client Initial must be delivered as a socket-free incoming datagram"),
    };
    let (_, mut server) = server_endpoint
        .accept(incoming, now, &mut endpoint_buffer, None)
        .unwrap();

    // Timer scheduling and firing are likewise driven solely by caller-supplied Instants.
    assert!(client.poll_timeout().is_some());
    client.handle_timeout(now);

    // These calls compile against the exact stream surface the private adapter will use.
    // The handshake has not completed, so stream I/O is expected to remain unavailable.
    assert!(client.streams().open(Dir::Bi).is_none());
    let client_stream = StreamId::new(quinn_proto::Side::Client, Dir::Bi, 0);
    assert!(client.send_stream(client_stream).write(b"request").is_err());
    let mut receive_stream = server.recv_stream(client_stream);
    let _pending_read = receive_stream.read(true);

    // qlog is an in-memory metadata path; no file, socket, or secret exporter is involved.
    assert!(!qlog.0.lock().unwrap().is_empty());
}
